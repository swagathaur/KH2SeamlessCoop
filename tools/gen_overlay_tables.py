#!/usr/bin/env python3
"""Turn each overlay's register_functions.cpp into a namespaced dispatch table.

ps2_recomp has no notion of overlays: run over an overlay ELF it emits a
register_functions.cpp that defines the program-wide table globals
(g_ps2RecompiledFunctionTable*), which the main executable also defines. That
file is left out of the build and re-emitted here as

    namespace kh2ovl::<name> { PS2Runtime::FunctionRegion &functionRegion(); }

plus generated/overlays/overlay_registry.cpp, which lists every overlay with
the word found at arena offset +0x14 in its image. Each KH2 overlay begins with
a different `j <entry>` there, so the runtime identifies the resident overlay
by reading that one word (see port/runtime/overlay_manager.cpp).

Adapted from DQ8Recomp's tools/mwo3/gen_overlay_table.py (GPL-3.0).

Usage: gen_overlay_tables.py   (run from the repository root)
"""
import re
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OVERLAYS = ["title", "movie", "shop", "gumimenu", "gumibattle"]
SIGNATURE_OFFSET = 0x14

EXTERN_RE = re.compile(
    r"^extern const uint32_t g_ps2RecompiledFunctionTable(Base|End|SlotCount) = ([0-9a-fA-Fxu]+);", re.M)
ENTRY_RE = re.compile(
    r"^\s*g_ps2RecompiledFunctionTable\[(\d+)\]\s*=\s*([A-Za-z_][A-Za-z0-9_]*)\s*;\s*(//.*)?$")

TABLE = """// GENERATED by tools/gen_overlay_tables.py -- do not edit.
// Replaces ps2_recomp's register_functions.cpp for overlay '{name}'.
#include "ps2_runtime.h"
#include "ps2_recompiled_functions.h"

namespace kh2ovl::{name}
{{
namespace
{{
constexpr uint32_t kBase = {base}u;
constexpr uint32_t kEnd = {end}u;
constexpr uint32_t kSlotCount = {slots}u;
PS2Runtime::RecompiledFunction g_slots[kSlotCount] = {{}};

PS2Runtime::FunctionRegion buildRegion()
{{
{entries}    return PS2Runtime::FunctionRegion{{kBase, kEnd, kSlotCount, g_slots}};
}}
}} // namespace

PS2Runtime::FunctionRegion &functionRegion()
{{
    static PS2Runtime::FunctionRegion region = buildRegion();
    return region;
}}
}} // namespace kh2ovl::{name}
"""

REGISTRY = """// GENERATED by tools/gen_overlay_tables.py -- do not edit.
#include "overlay_manager.h"

{decls}
namespace kh2ovl
{{
const OverlayInfo kOverlays[] = {{
{rows}}};
const size_t kOverlayCount = sizeof(kOverlays) / sizeof(kOverlays[0]);
}} // namespace kh2ovl
"""


def convert(name: str) -> None:
    out_dir = ROOT / "generated" / f"ovl_{name}"
    text = (out_dir / "register_functions.cpp").read_text(encoding="utf-8")
    fields = dict(EXTERN_RE.findall(text))
    entries = []
    for line in text.splitlines():
        m = ENTRY_RE.match(line)
        if m:
            entries.append(f"    g_slots[{m.group(1)}] = ::{m.group(2)}; {m.group(3) or ''}".rstrip() + "\n")
    if not entries or set(fields) != {"Base", "End", "SlotCount"}:
        raise SystemExit(f"{out_dir}/register_functions.cpp: unexpected format")
    (out_dir / f"overlay_table_{name}.cpp").write_text(TABLE.format(
        name=name, base=fields["Base"].rstrip("u"), end=fields["End"].rstrip("u"),
        slots=fields["SlotCount"].rstrip("u"), entries="".join(entries)), encoding="utf-8")
    print(f"ovl_{name}: {len(entries)} table entries, {fields['Base']}..{fields['End']}")


def main():
    decls, rows = [], []
    for name in OVERLAYS:
        convert(name)
        image = (ROOT / "game" / "overlays" / f"ovl_{name}.x").read_bytes()
        sig = struct.unpack_from("<I", image, SIGNATURE_OFFSET)[0]
        decls.append(f"namespace kh2ovl::{name} {{ PS2Runtime::FunctionRegion &functionRegion(); }}")
        rows.append(f'    {{"{name}", 0x{sig:08X}u, {len(image)}u, &kh2ovl::{name}::functionRegion}},\n')
    reg = ROOT / "generated" / "overlays" / "overlay_registry.cpp"
    reg.parent.mkdir(parents=True, exist_ok=True)
    reg.write_text(REGISTRY.format(decls="\n".join(decls), rows="".join(rows)), encoding="utf-8")
    print(f"wrote {reg.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
