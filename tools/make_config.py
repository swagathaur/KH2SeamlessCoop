#!/usr/bin/env python3
"""Write the ps2_recomp configs for the main ELF and each overlay.

  config/kh2.toml              main executable (committed; paths are relative)
  config/functions.recomp.csv  the main map as handed to ps2_recomp (see KEEP_AS_GUEST)
  config/overlays/<name>.toml  one per overlay, each with its own function map

Inputs:
  config/functions.csv              main function map (make_function_map.py)
  config/stubs.fragment.toml        vetted SDK stubs (gen_stubs.py)
  config/analyzer/analyzer.toml     ps2_analyzer output, for the [mmio] table
  config/functions_<ovl>.csv        overlay maps (Ghidra, tools/ghidra)

Policy (follows DQ8Recomp): no instruction patches. The analyzer's
"potential self-modifying code" NOPs land inside Sony's own libraries and would
silently change behaviour; problems are fixed in the runtime instead.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OVERLAYS = ["title", "movie", "shop", "gumimenu", "gumibattle"]

# SDK functions that must run as guest code although the runtime implements a
# function of the same name. ps2_recomp stubs any function whose name is in the
# runtime's stub list (also with a leading underscore stripped), whatever the
# [stubs] table says, so these are renamed guest_<name> in the map it reads.
#
# Known gap: newlib's _malloc_r, _free_r, _calloc_r, malloc_extend_top and
# __malloc_lock are stubbed by name the same way, although gen_stubs.py lists
# them in DO_NOT_STUB. Boot works with the runtime's allocator; moving the C
# heap back to the guest is a separate change (docs/boot-log.md).
KEEP_AS_GUEST = {
    "sceGsSetDefDispEnv": "runtime version builds non-hardware DISPLAY values",
}

HEADER = """# Generated by tools/make_config.py -- edit that script, not this file.
# Paths are relative to the repository root (ps2_recomp runs from there).
"""


def mmio_section(analyzer: Path) -> str:
    text = analyzer.read_text(encoding="utf-8")
    m = re.search(r"^\[mmio\]\n(.*?)(?=^\[|\Z)", text, re.S | re.M)
    if not m:
        return ""
    lines = [l for l in m.group(1).splitlines() if re.match(r'^"0x', l)]
    return "[mmio]\n" + "\n".join(lines) + "\n"


def general(input_path, csv, output, stubs_block):
    return f"""[general]
input = "{input_path}"
ghidra_output = "{csv}"
output = "{output}"
single_file_output = false
low_memory_mode = false
output_worker_threads = 0
patch_syscalls = false
patch_cop0 = true
patch_cache = true
{stubs_block}
skip = []
"""


def write_recomp_map(src: Path, dst: Path) -> int:
    lines = src.read_text(encoding="utf-8").splitlines()
    renamed = 0
    out = []
    for line in lines:
        name, sep, rest = line.partition(",")
        if name in KEEP_AS_GUEST:
            line = f"guest_{name}{sep}{rest}"
            renamed += 1
        out.append(line)
    dst.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    return renamed


def main():
    renamed = write_recomp_map(ROOT / "config/functions.csv", ROOT / "config/functions.recomp.csv")
    print(f"config/functions.recomp.csv: {renamed} of {len(KEEP_AS_GUEST)} guest-only functions renamed")
    stubs = (ROOT / "config/stubs.fragment.toml").read_text(encoding="utf-8").strip()
    # No [mmio] table. ps2_analyzer derives each site's address from the
    # nearest `lui` only and ignores the `ori`/`addiu` that completes it, so 130
    # of its 142 entries say 0x10000000 (TIMER0); ps2_recomp then hard-codes
    # that address, e.g. libvu1's VIF1_STAT poll at 0x00134080 read TIMER0 and
    # spun forever. Without the table every load/store checks its computed
    # address at run time (READ32/WRITE32 route I/O and scratchpad to the
    # runtime), which is always right.
    mmio = ""
    main_cfg = HEADER + general("game/SLPM_666.75", "config/functions.recomp.csv",
                                "generated/main", stubs)
    (ROOT / "config/kh2.toml").write_text(main_cfg, encoding="utf-8", newline="\n")
    print(f"config/kh2.toml: {stubs.count('@0x')} stubs, no mmio table (see comment)")

    outdir = ROOT / "config/overlays"
    outdir.mkdir(exist_ok=True)
    for name in OVERLAYS:
        cfg = HEADER + "# Overlay: calls into the main executable resolve through its table.\n"
        cfg += general(f"build/overlays/{name}.elf", f"config/functions_{name}.csv",
                       f"generated/ovl_{name}", "stubs = []")
        (outdir / f"{name}.toml").write_text(cfg, encoding="utf-8", newline="\n")
    print(f"config/overlays/: {len(OVERLAYS)} overlay configs")


if __name__ == "__main__":
    main()
